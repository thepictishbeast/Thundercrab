/// What the user did. Flat mirror of [`thundercrab_core::FlagSource`].
#[derive(uniffi::Enum, Clone, Copy, Debug)]
pub enum FfiFlagSource {
    /// User moved a message into a folder.
    ManualMove,
    /// User toggled the "Important" flag (or equivalent).
    ToggleFlag,
    /// User explicitly categorized the message.
    ExplicitCategory,
    /// User accepted a federated suggestion.
    AcceptSuggestion,
}

impl From<FfiFlagSource> for FlagSource {
    fn from(s: FfiFlagSource) -> Self {
        match s {
            FfiFlagSource::ManualMove => Self::ManualMove,
            FfiFlagSource::ToggleFlag => Self::ToggleFlag,
            FfiFlagSource::ExplicitCategory => Self::ExplicitCategory,
            FfiFlagSource::AcceptSuggestion => Self::AcceptSuggestion,
        }
    }
}

/// A flag-event observation. FEATURES ONLY — no body, no full address. The
/// `[u8; 32]` hash is bridged to `Vec<u8>` (validated to length 32 at the
/// seam); the `DateTime<Utc>` is bridged to epoch seconds.
#[derive(uniffi::Record, Clone, Debug)]
pub struct FfiFlagEvent {
    /// Per-message stable id (32-byte blake3 hash).
    pub message_hash: Vec<u8>,
    /// What the user did.
    pub source: FfiFlagSource,
    /// Destination folder (for moves) or flag name (for toggles).
    pub destination: String,
    /// Sender domain *with* leading `@`. Empty if not parseable.
    pub from_domain_with_at: String,
    /// Lowercased List-Id value (without angle brackets), if present.
    pub list_id: Option<String>,
    /// `true` if a List-Unsubscribe header was present.
    pub has_list_unsubscribe: bool,
    /// Lowercased subject tokens (stop-words removed).
    pub subject_tokens: Vec<String>,
    /// `X-Priority` value if 1 or 2.
    pub priority_high: bool,
    /// When the flag happened, UTC epoch seconds.
    pub observed_at: i64,
}

impl TryFrom<&FfiFlagEvent> for FlagEvent {
    type Error = FfiError;

    fn try_from(e: &FfiFlagEvent) -> Result<Self, Self::Error> {
        let message_hash: [u8; 32] = e
            .message_hash
            .as_slice()
            .try_into()
            .map_err(|_| FfiError::InvalidInput {
                detail: format!(
                    "message_hash must be exactly 32 bytes, got {}",
                    e.message_hash.len()
                ),
            })?;
        let observed_at: DateTime<Utc> =
            Utc.timestamp_opt(e.observed_at, 0).single().ok_or_else(|| {
                FfiError::InvalidInput {
                    detail: format!("observed_at is not a valid epoch second: {}", e.observed_at),
                }
            })?;
        Ok(Self {
            local_id: None,
            message_hash,
            source: e.source.into(),
            destination: e.destination.clone(),
            from_domain_with_at: e.from_domain_with_at.clone(),
            list_id: e.list_id.clone(),
            has_list_unsubscribe: e.has_list_unsubscribe,
            subject_tokens: e.subject_tokens.clone(),
            priority_high: e.priority_high,
            observed_at,
        })
    }
}

