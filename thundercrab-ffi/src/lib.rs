/// Open the local store at `db_path`, run `f`, close it. The `Db` is not
/// `Send`/long-lived across FFI; each call is a short open-do-close so the
/// store is never held across the boundary.
fn with_db<T>(db_path: &str, f: impl FnOnce(&Db) -> Result<T, FfiError>) -> Result<T, FfiError> {
    let db = Db::open(db_path)?;
    f(&db)
}

/// Record a flag-event observation in the local store.
///
/// # Errors
/// `InvalidInput` if the event's hash/timestamp are malformed; `Protocol` for
/// store failures.
#[uniffi::export]
pub fn record_flag_event(db_path: String, ev: FfiFlagEvent) -> Result<(), FfiError> {
    let event = FlagEvent::try_from(&ev)?;
    with_db(&db_path, |db| {
        db.record_flag(&event)?;
        Ok(())
    })
}

/// Upsert a rule into the local store.
///
/// # Errors
/// `InvalidInput` if the rule's JSON AST is malformed; `Protocol` for store
/// failures.
#[uniffi::export]
pub fn save_rule(db_path: String, rule: FfiCrabRule) -> Result<(), FfiError> {
    let core = CrabRule::try_from(&rule)?;
    with_db(&db_path, |db| {
        db.save_rule(&core)?;
        Ok(())
    })
}

/// Load every rule from the local store, score-desc then id-asc.
///
/// # Errors
/// `Protocol` for store / serialization failures.
#[uniffi::export]
pub fn load_rules(db_path: String) -> Result<Vec<FfiCrabRule>, FfiError> {
    with_db(&db_path, |db| {
        db.load_rules()?
            .iter()
            .map(FfiCrabRule::try_from)
            .collect()
    })
}

/// Delete a rule by id. Returns `true` if a row was removed.
///
/// # Errors
/// `Protocol` for store failures.
#[uniffi::export]
pub fn delete_rule(db_path: String, id: String) -> Result<bool, FfiError> {
    with_db(&db_path, |db| Ok(db.delete_rule(&id)?))
}

/// Render `rules` into a complete personal Sieve script (RFC 5228) ready for
/// [`push_sieve`]. Pure + blocking; performs no I/O.
///
/// The result is a *personal* active script that layers on top of the server's
/// global `sieve_before` (it does not replace server-side category sorting). The
/// emitter is validated against Dovecot's `sievec` in `thundercrab-core`.
///
/// SECURITY: emits only header / Subject / From-domain tests + fileinto/setflag
/// actions; the rule AST has no body-touching variant.
///
/// # Errors
/// `InvalidInput` if any rule's `when_json` / `action_json` is malformed.
#[uniffi::export]
pub fn rules_to_sieve(rules: Vec<FfiCrabRule>) -> Result<String, FfiError> {
    let core: Vec<CrabRule> =
        rules.iter().map(CrabRule::try_from).collect::<Result<_, _>>()?;
    Ok(to_sieve(&core))
}

/// Read-only preview of derived rule suggestions: derives candidates from the
/// local flag-event grouping, then runs each through the suggestion safety gate
/// (`apply_suggestion`), returning only those that pass. No rule is persisted
/// or auto-applied — this is a preview the UI shows for one-click acceptance.
///
/// `min_obs` — drop domain/destination pairs below this observation count.
/// `dominance` — the destination must account for at least this fraction
/// (`0.0..=1.0`) of the domain's events.
///
/// # Errors
/// `Protocol` for store failures; `InvalidInput` if a candidate fails the
/// safety gate or cannot be re-serialized.
#[uniffi::export]
pub fn preview_suggestions(
    db_path: String,
    min_obs: i64,
    dominance: f64,
) -> Result<Vec<FfiCrabRule>, FfiError> {
    with_db(&db_path, |db| {
        let counts = db.flag_counts_by_domain_dest()?;
        let candidates = derive_rule_candidates(&counts, min_obs, dominance);
        let mut out = Vec::with_capacity(candidates.len());
        for cand in &candidates {
            // apply_suggestion both validates (fail-closed on protected
            // folders/flags) and re-marks origin=Federated + clamps score.
            let safe = apply_suggestion(&cand.rule)?;
            out.push(FfiCrabRule::try_from(&safe)?);
        }
        Ok(out)
    })
}

