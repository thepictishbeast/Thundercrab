    #[test]
    fn store_record_and_load_round_trip() {
        // Use a temp file DB (Db::open needs a path; :memory: is per-conn and
        // with_db opens a fresh conn each call, so an in-memory DB wouldn't
        // persist across the record/load calls).
        let dir = std::env::temp_dir();
        let path = dir.join(format!("tc_ffi_test_{}.db", std::process::id()));
        let path_str = path.to_string_lossy().to_string();
        let _ = std::fs::remove_file(&path);

        let rule = FfiCrabRule {
            id: "x".into(),
            display_name: "X".into(),
            when_json: r#"{"kind":"always"}"#.into(),
            action_json: r#"{"kind":"file_into","folder":"Forums"}"#.into(),
            score: 75,
            stop_on_match: true,
            origin: FfiRuleOrigin::User,
        };
        save_rule(path_str.clone(), rule).expect("save");
        let loaded = load_rules(path_str.clone()).expect("load");
        assert_eq!(loaded.len(), 1);
        assert_eq!(loaded[0].id, "x");
        assert!(delete_rule(path_str.clone(), "x".into()).expect("delete"));

        let _ = std::fs::remove_file(&path);
    }

    #[test]
    fn preview_suggestions_returns_safe_candidates() {
        let dir = std::env::temp_dir();
        let path = dir.join(format!("tc_ffi_sugg_{}.db", std::process::id()));
        let path_str = path.to_string_lossy().to_string();
        let _ = std::fs::remove_file(&path);

        // Record a clear signal: @clear.com → Promotions, 4 distinct events.
        for h in 0..4u8 {
            let ev = FfiFlagEvent {
                message_hash: vec![h; 32],
                source: FfiFlagSource::ManualMove,
                destination: "Promotions".into(),
                from_domain_with_at: "@clear.com".into(),
                list_id: None,
                has_list_unsubscribe: false,
                subject_tokens: vec![],
                priority_high: false,
                observed_at: 1_700_000_000,
            };
            record_flag_event(path_str.clone(), ev).expect("record");
        }
        let suggestions = preview_suggestions(path_str.clone(), 3, 0.7).expect("preview");
        assert_eq!(suggestions.len(), 1);
        // Safety gate re-marks origin=Federated.
        assert!(matches!(suggestions[0].origin, FfiRuleOrigin::Federated));
        assert!(suggestions[0].when_json.contains("@clear.com"));

        let _ = std::fs::remove_file(&path);
    }
