/// A live, authenticated IMAP client. Concrete `#[derive(uniffi::Object)]`
/// wrapping the (non-dyn-compatible, RPITIT) [`RustImapBackend`]. The inner
/// backend is held as `Mutex<Option<…>>` so the consuming `logout` can `.take()`
/// it, leaving the object inert afterward.
#[derive(uniffi::Object)]
pub struct ThunderCrabClient {
    inner: Mutex<Option<RustImapBackend>>,
}

/// Connect to the configured IMAPS host and authenticate. The password is
/// consumed and dropped after `LOGIN` (per the real `RustImapBackend::connect`).
/// A free async fn — not a `#[uniffi::constructor]` — because it must return
/// `Result` and does not rely on 0.28's async-constructor support.
///
/// # Errors
/// `Transport` if TCP/TLS/greeting fails; `Auth` if `LOGIN` is rejected.
#[uniffi::export(async_runtime = "tokio")]
pub async fn connect(
    cfg: FfiAccountConfig,
    password: String,
) -> Result<Arc<ThunderCrabClient>, FfiError> {
    let account = AccountConfig::from(&cfg);
    let backend = RustImapBackend::connect(&account, &password).await?;
    Ok(Arc::new(ThunderCrabClient {
        inner: Mutex::new(Some(backend)),
    }))
}

#[uniffi::export(async_runtime = "tokio")]
impl ThunderCrabClient {
    /// List all folders the user can see.
    ///
    /// # Errors
    /// `Protocol` on IMAP failure; `NotImplemented` if the client was already
    /// logged out.
    pub async fn list_folders(&self) -> Result<Vec<FfiFolder>, FfiError> {
        let guard = self.inner.lock().await;
        let backend = guard.as_ref().ok_or_else(client_gone)?;
        let folders = backend.list_folders().await?;
        Ok(folders
            .into_iter()
            .map(|f| FfiFolder {
                name: f.name,
                special_use: f.special_use,
                messages: f.messages,
                unseen: f.unseen,
            })
            .collect())
    }

    /// Fetch headers for messages in `folder`, optionally limited to the most
    /// recent `limit`. HEADER-ONLY (`BODY.PEEK[HEADER]`) — no body is read.
    ///
    /// # Errors
    /// `Protocol` on IMAP failure; `NotImplemented` if already logged out.
    pub async fn fetch_headers(
        &self,
        folder: String,
        limit: Option<u32>,
    ) -> Result<Vec<FfiHeaders>, FfiError> {
        let guard = self.inner.lock().await;
        let backend = guard.as_ref().ok_or_else(client_gone)?;
        let headers = backend.fetch_headers(&folder, limit).await?;
        Ok(headers
            .into_iter()
            .map(|h| FfiHeaders {
                uid: h.uid,
                folder: h.folder,
                from: h.from,
                subject: h.subject,
                other_headers: h
                    .other_headers
                    .into_iter()
                    .map(|(name, value)| FfiHeader { name, value })
                    .collect(),
            })
            .collect())
    }

    /// Move `uid` from `from_folder` to `to_folder` (the IMAP side of a
    /// recorded flag-event move).
    ///
    /// # Errors
    /// `Protocol` on IMAP failure; `NotImplemented` if already logged out.
    pub async fn move_message(
        &self,
        from_folder: String,
        to_folder: String,
        uid: u32,
    ) -> Result<(), FfiError> {
        let guard = self.inner.lock().await;
        let backend = guard.as_ref().ok_or_else(client_gone)?;
        backend.move_message(&from_folder, &to_folder, uid).await?;
        Ok(())
    }

    /// Set or clear an IMAP `flag` on `uid` in `folder` (the IMAP side of a
    /// recorded flag-event toggle).
    ///
    /// # Errors
    /// `Protocol` on IMAP failure; `NotImplemented` if already logged out.
    pub async fn set_flag(
        &self,
        folder: String,
        uid: u32,
        flag: String,
        set: bool,
    ) -> Result<(), FfiError> {
        let guard = self.inner.lock().await;
        let backend = guard.as_ref().ok_or_else(client_gone)?;
        backend.set_flag(&folder, uid, &flag, set).await?;
        Ok(())
    }

    /// Fetch a message body. NOT IMPLEMENTED: `thundercrab-imap` exposes no
    /// body-reading method, and adding one (a `BODY.PEEK[]` fetch + a MIME
    /// parser) is a display-only carve-out gated on explicit ratification and
    /// walled off from the rules/suggestions/ledger spine. Until then this is a
    /// hard `NotImplemented`.
    ///
    /// # Errors
    /// Always `NotImplemented`.
    #[allow(clippy::unused_async)] // signature parity with the future real impl
    pub async fn fetch_body(&self, _folder: String, _uid: u32) -> Result<String, FfiError> {
        Err(FfiError::NotImplemented {
            detail: "fetch_body: reading message bodies is gated and unimplemented".to_string(),
        })
    }

    /// Log out cleanly. Consumes the inner backend via `.take()`; subsequent
    /// calls on this client return `NotImplemented`. Best-effort — a failed
    /// logout drops the session anyway.
    pub async fn logout(&self) {
        let backend = {
            let mut guard = self.inner.lock().await;
            guard.take()
        };
        if let Some(backend) = backend {
            backend.logout().await;
        }
    }
}

/// `NotImplemented` produced when an operation is attempted on a client whose
/// backend was already taken by `logout`.
fn client_gone() -> FfiError {
    FfiError::NotImplemented {
        detail: "client has been logged out".to_string(),
    }
}

