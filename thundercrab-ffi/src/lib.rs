/// Where a rule came from. Flat mirror of [`thundercrab_core::RuleOrigin`].
#[derive(uniffi::Enum, Clone, Copy, Debug)]
pub enum FfiRuleOrigin {
    /// User created or accepted this rule explicitly.
    User,
    /// Shipped with the platform.
    Platform,
    /// Came from the federated suggestion ledger.
    Federated,
}

impl From<FfiRuleOrigin> for RuleOrigin {
    fn from(o: FfiRuleOrigin) -> Self {
        match o {
            FfiRuleOrigin::User => Self::User,
            FfiRuleOrigin::Platform => Self::Platform,
            FfiRuleOrigin::Federated => Self::Federated,
        }
    }
}

impl From<RuleOrigin> for FfiRuleOrigin {
    fn from(o: RuleOrigin) -> Self {
        match o {
            RuleOrigin::User => Self::User,
            RuleOrigin::Platform => Self::Platform,
            RuleOrigin::Federated => Self::Federated,
        }
    }
}

/// A sorting rule at the FFI seam. The `when`/`action` AST is carried as
/// canonical serde JSON strings (`when_json` / `action_json`) so the
/// byte-identical [`MatchExpr`] / [`Action`] AST is produced and consumed by
/// core serde — never re-serialized in Kotlin. This is what keeps the rule
/// wire-compatible with `mail_config::CategoryRule`.
#[derive(uniffi::Record, Clone, Debug)]
pub struct FfiCrabRule {
    /// Stable id.
    pub id: String,
    /// Human-readable name.
    pub display_name: String,
    /// Match condition, as canonical [`MatchExpr`] JSON.
    pub when_json: String,
    /// Action(s), as canonical [`Action`] JSON.
    pub action_json: String,
    /// Higher = wins.
    pub score: i32,
    /// If `true`, no further rules evaluate after this fires.
    pub stop_on_match: bool,
    /// Provenance.
    pub origin: FfiRuleOrigin,
}

impl TryFrom<&FfiCrabRule> for CrabRule {
    type Error = FfiError;

    fn try_from(r: &FfiCrabRule) -> Result<Self, Self::Error> {
        let when: MatchExpr =
            serde_json::from_str(&r.when_json).map_err(|e| FfiError::InvalidInput {
                detail: format!("when_json: {e}"),
            })?;
        let action: Action =
            serde_json::from_str(&r.action_json).map_err(|e| FfiError::InvalidInput {
                detail: format!("action_json: {e}"),
            })?;
        Ok(Self {
            id: r.id.clone(),
            display_name: r.display_name.clone(),
            when,
            action,
            score: r.score,
            stop_on_match: r.stop_on_match,
            origin: r.origin.into(),
        })
    }
}

impl TryFrom<&CrabRule> for FfiCrabRule {
    type Error = FfiError;

    fn try_from(r: &CrabRule) -> Result<Self, Self::Error> {
        let when_json = serde_json::to_string(&r.when).map_err(|e| FfiError::Protocol {
            detail: format!("serialize when: {e}"),
        })?;
        let action_json = serde_json::to_string(&r.action).map_err(|e| FfiError::Protocol {
            detail: format!("serialize action: {e}"),
        })?;
        Ok(Self {
            id: r.id.clone(),
            display_name: r.display_name.clone(),
            when_json,
            action_json,
            score: r.score,
            stop_on_match: r.stop_on_match,
            origin: r.origin.into(),
        })
    }
}

