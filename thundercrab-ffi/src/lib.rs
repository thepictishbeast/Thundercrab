//! `thundercrab-ffi` — the UniFFI surface that native UIs (Android Compose
//! first, then a Linux desktop UI) call into. The Rust core stays the single
//! source of truth; this crate is a thin, logic-free pass-through.
//!
//! BUG ASSUMPTION: every function here is a trivial forwarder. If real logic
//! appears in this crate, that's the bug — it belongs in `thundercrab-core`,
//! `thundercrab-imap`, or `thundercrab-suggestions`. The *only* work this
//! layer is allowed to do is shape-translation at the FFI seam: bridging types
//! UniFFI cannot represent (tuples, fixed-size arrays, `DateTime`, the
//! `MatchExpr`/`Action` AST) to/from the canonical core types. No business
//! logic, no rule evaluation, no protocol decisions.
//!
//! SECURITY: nothing here touches message bodies (the core invariant). The
//! exposed surface is config + folder/header-level operations + the rule and
//! flag-event stores. `fetch_body` exists only as a `NotImplemented` stub —
//! reading bodies is gated on explicit ratification and a new IMAP method that
//! does not exist yet (see the stub's docs).
//!
//! Bindings are generated by `uniffi-bindgen` during the platform build
//! (Kotlin for Android, Swift for iOS). See docs/ROADMAP-ANDROID-FIRST.md.

