/// Send one message. Connects, authenticates, sends, closes — the password is
/// taken per call and dropped after the send. Pure forwarder to
/// [`thundercrab_imap::smtp::send_message`].
///
/// # Errors
/// `Transport` / `Auth` / `Protocol` from the SMTP layer; `InvalidInput` if an
/// address is unparseable (surfaced by the SMTP layer as `Protocol`).
#[uniffi::export(async_runtime = "tokio")]
pub async fn send_message(
    cfg: FfiAccountConfig,
    password: String,
    encryption: FfiSmtpEncryption,
    message: FfiOutboundMessage,
) -> Result<(), FfiError> {
    let account = AccountConfig::from(&cfg);
    // Rebuild the borrowing OutboundMessage<'a> view from the owned strings.
    let to: Vec<&str> = message.to.iter().map(String::as_str).collect();
    let cc: Vec<&str> = message.cc.iter().map(String::as_str).collect();
    let outbound = OutboundMessage {
        from: message.from.as_str(),
        to: &to,
        cc: &cc,
        subject: message.subject.as_str(),
        body: message.body.as_str(),
    };
    smtp::send_message(&account, &password, encryption.into(), &outbound).await?;
    Ok(())
}

/// Push an active Sieve script via `ManageSieve`. Takes the password and the
/// `script_name` per call — neither is available on the `Backend::put_sieve`
/// trait method (which is `NotImplemented` by design), so this forwards to the
/// standalone [`thundercrab_imap::managesieve::put_active_script`].
///
/// # Errors
/// `Transport` / `Auth` / `Protocol` from the `ManageSieve` layer.
#[uniffi::export(async_runtime = "tokio")]
pub async fn push_sieve(
    cfg: FfiAccountConfig,
    password: String,
    script_name: String,
    script: String,
) -> Result<(), FfiError> {
    let account = AccountConfig::from(&cfg);
    managesieve::put_active_script(&account, &password, &script_name, &script).await?;
    Ok(())
}

