/// Open the local store at `db_path`, run `f`, close it. The `Db` is not
/// `Send`/long-lived across FFI; each call is a short open-do-close so the
/// store is never held across the boundary.
fn with_db<T>(db_path: &str, f: impl FnOnce(&Db) -> Result<T, FfiError>) -> Result<T, FfiError> {
    let db = Db::open(db_path)?;
    f(&db)
}

