/// Render `rules` into a complete personal Sieve script (RFC 5228) ready for
/// [`push_sieve`]. Pure + blocking; performs no I/O.
///
/// The result is a *personal* active script that layers on top of the server's
/// global `sieve_before` (it does not replace server-side category sorting). The
/// emitter is validated against Dovecot's `sievec` in `thundercrab-core`.
///
/// SECURITY: emits only header / Subject / From-domain tests + fileinto/setflag
/// actions; the rule AST has no body-touching variant.
///
/// # Errors
/// `InvalidInput` if any rule's `when_json` / `action_json` is malformed.
#[uniffi::export]
pub fn rules_to_sieve(rules: Vec<FfiCrabRule>) -> Result<String, FfiError> {
    let core: Vec<CrabRule> =
        rules.iter().map(CrabRule::try_from).collect::<Result<_, _>>()?;
    Ok(to_sieve(&core))
}

/// Read-only preview of derived rule suggestions: derives candidates from the
/// local flag-event grouping, then runs each through the suggestion safety gate
/// (`apply_suggestion`), returning only those that pass. No rule is persisted
/// or auto-applied — this is a preview the UI shows for one-click acceptance.
///
/// `min_obs` — drop domain/destination pairs below this observation count.
/// `dominance` — the destination must account for at least this fraction
/// (`0.0..=1.0`) of the domain's events.
///
/// # Errors
/// `Protocol` for store failures; `InvalidInput` if a candidate fails the
/// safety gate or cannot be re-serialized.
#[uniffi::export]
pub fn preview_suggestions(
    db_path: String,
    min_obs: i64,
    dominance: f64,
) -> Result<Vec<FfiCrabRule>, FfiError> {
    with_db(&db_path, |db| {
        let counts = db.flag_counts_by_domain_dest()?;
        let candidates = derive_rule_candidates(&counts, min_obs, dominance);
        let mut out = Vec::with_capacity(candidates.len());
        for cand in &candidates {
            // apply_suggestion validates (fail-closed on protected folders/flags)
            // and re-marks origin=Federated + clamps score. A candidate that FAILS
            // the gate is SKIPPED — preview returns only those that pass, and never
            // errors the whole batch over a single unsafe candidate (its doc
            // contract). A real serialization failure on a *safe* rule still errors.
            let Ok(safe) = apply_suggestion(&cand.rule) else { continue };
            out.push(FfiCrabRule::try_from(&safe)?);
        }
        Ok(out)
    })
}

